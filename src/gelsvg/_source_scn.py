"""A Bio-Rad Image Lab `.scn` source file (§5.4 `scn`): a MIME multipart
document of XML parts and one part of pixels."""

from __future__ import annotations

import re
from xml.parsers import expat

import numpy as np

from . import _formal
from ._sourcebase import DAMAGED, NOT_A_SOURCE_IMAGE, Decoded, SourceError

MARK = b"Generated by Image Lab"
_BOUNDARY = re.compile(r'boundary="?([^";]+)"?')


class _Refused(Exception):
    pass


def is_scn(data: bytes) -> bool:
    return MARK in data[:64]


def _header_value(text: str) -> str:
    name, _, value = text.partition(" ")
    value = value.strip()
    if not value:
        raise SourceError(DAMAGED, f"The .scn header {name} has no value.")
    return value


def _parts(data: bytes) -> tuple[list[bytes], int, int]:
    """The XML parts, and the offset and length of the first
    `application/octet-stream` part."""

    xml_parts: list[bytes] = []
    pixel_offset = pixel_length = None
    boundary, content_type, length = b"", "", 0
    pos = 0
    while pos < len(data):
        end = data.find(b"\n", pos)
        if end < 0:
            line, pos = data[pos:], len(data)
        else:
            line, pos = data[pos:end], end + 1
        stripped = line.strip()
        text = stripped.decode("utf-8", errors="replace")
        if text.startswith("Content-Type"):
            value = _header_value(text)
            content_type = value.split(";", 1)[0].strip()
            match = _BOUNDARY.search(value)
            if match:
                boundary = match.group(1).encode()
        elif boundary and stripped == b"--" + boundary:
            length = 0
        elif text.startswith("Content-Length"):
            try:
                length = int(_header_value(text))
            except ValueError:
                raise SourceError(DAMAGED, "A .scn Content-Length is not a number.") from None
            if length < 0:
                raise SourceError(DAMAGED, "A .scn Content-Length is negative.")
        elif stripped == b"" and content_type in ("text/xml", "application/octet-stream"):
            if length > len(data) - pos:
                raise SourceError(DAMAGED, "A .scn part runs past the end of the file.")
            if content_type == "text/xml":
                xml_parts.append(data[pos : pos + length])
            elif pixel_offset is None:
                pixel_offset, pixel_length = pos, length
            pos += length
            content_type = ""
    if pixel_offset is None:
        raise SourceError(DAMAGED, "The .scn file has no part of pixels.")
    return xml_parts, pixel_offset, pixel_length


def _facts(xml_parts: list[bytes]) -> dict[str, str]:
    """The first value of each fact §5.4 reads, through all XML parts."""

    facts: dict[str, str] = {}
    for part in xml_parts:
        texts: list[list] = []

        def start(name, attrs):
            local = name.rsplit(" ", 1)[-1]
            if local == "size_pix":
                for key in ("width", "height"):
                    if key in attrs:
                        facts.setdefault(f"size_pix {key}", attrs[key])
            elif local == "scanner" and "max_value" in attrs:
                facts.setdefault("scanner max_value", attrs["max_value"])
            texts.append([local, ""])

        def end(_name):
            local, text = texts.pop()
            if local in ("endian", "channel_count") and text.strip():
                facts.setdefault(local, text.strip())

        def data(text):
            if texts:
                texts[-1][1] += text

        def refuse(*_args):
            raise _Refused()

        parser = expat.ParserCreate(namespace_separator=" ")
        parser.StartElementHandler, parser.EndElementHandler, parser.CharacterDataHandler = start, end, data
        parser.EntityDeclHandler = parser.ExternalEntityRefHandler = refuse
        try:
            parser.Parse(part, True)
        except (expat.ExpatError, _Refused):
            continue  # a part that cannot be read tells nothing
    return facts


def read(data: bytes) -> Decoded:
    xml_parts, offset, length = _parts(data)
    facts = _facts(xml_parts)
    try:
        width, height = int(facts["size_pix width"]), int(facts["size_pix height"])
    except (KeyError, ValueError):
        raise SourceError(DAMAGED, "The .scn file does not say its image size.") from None
    if width <= 0 or height <= 0:
        raise SourceError(DAMAGED, "The .scn file's image size is not positive.")
    if "channel_count" in facts and facts["channel_count"] != "1":
        raise SourceError(NOT_A_SOURCE_IMAGE, f"The .scn file has {facts['channel_count']} channels.")
    try:
        max_value = int(facts["scanner max_value"]) if "scanner max_value" in facts else None
    except ValueError:
        max_value = None
    size = 1 if max_value is not None and max_value <= 256 else 2
    endian = ">" if facts.get("endian") == "big" else "<"
    pixel_bytes = width * height * size
    if length < pixel_bytes:
        raise SourceError(DAMAGED, "The .scn file's part of pixels is shorter than its image.")
    values = np.frombuffer(data, dtype=f"{endian}u{size}", count=width * height, offset=offset)
    pixels = values.astype(np.uint8 if size == 1 else np.uint16).reshape(height, width)
    before, after = data[:offset], data[offset + pixel_bytes :]
    segments = [({"part": name}, part) for name, part in (("before_pixels", before), ("after_pixels", after)) if part]
    return Decoded("scn", pixels, _formal.build("scn", segments))
